package com.example.Backend.usecase;

import com.example.Backend.domain.*; // 「*」はワイルドカード
import com.example.Backend.domain.object.*;
import com.example.Backend.domain.specification.ルール;
import com.example.Backend.domain.specification.ルール一覧;
import org.springframework.stereotype.Service;

@Service
public class 追加業務検知 {

    private final 時間割 時間割;
    private final アルバイト実施報告書 アルバイト実施報告書;
    private final カレンダー カレンダー;
    private final 労働情報表示 労働情報表示;

    public 追加業務検知(時間割 時間割, アルバイト実施報告書 アルバイト実施報告書, カレンダー カレンダー, 労働情報表示 労働情報表示) {
        this.時間割 = 時間割;
        this.アルバイト実施報告書 = アルバイト実施報告書;
        this.カレンダー = カレンダー;
        this.労働情報表示 = 労働情報表示;
    }

    void 実行する(選択した科目のデータ 選択した科目のデータ) {
        講義情報 講義情報 = 時間割.取得する(選択した科目のデータ); // 1

        アルバイト情報 アルバイト情報 = アルバイト実施報告書.取得する(選択した科目のデータ); // 2

        アルバイトの曜日 アルバイトの曜日 = カレンダー.曜日算出する(アルバイト情報.日にち()); // 3.1

        通常労働時間帯と追加労働時間帯 通常労働時間帯と追加労働時間帯 = null; // 初期化
        ルール<アルバイトの曜日> 曜日ルール = ルール一覧.曜日ルールを得る(講義情報.曜日()); // 曜日が一致しているか判定するクラスを生成

        if (!曜日ルール.判定する(アルバイトの曜日)) { // アルバイトの曜日と講義の曜日が不一致
            通常労働時間帯と追加労働時間帯 = 時間割.通常労働時間帯と追加労働時間帯を作る(アルバイト情報.労働時間帯(), 講義情報.講義時間帯());  // 3.2
        }

        if (曜日ルール.判定する(アルバイトの曜日)){ // アルバイトの曜日と講義の曜日が一致
            // 労働時間帯が講義時間帯に全て含まれる場合
            if (講義情報.講義時間帯().開始時間().compareTo(アルバイト情報.労働時間帯().開始時間()) <= 0 // 講義開始時間 が 労働開始時間 よりも 早い
                    &&  講義情報.講義時間帯().終了時間().compareTo(アルバイト情報.労働時間帯().終了時間()) >= 0) { // 講義終了時間 が 労働終了時間 よりも 遅い
                通常労働時間帯と追加労働時間帯 = 時間割.通常労働時間帯を作る(アルバイト情報.労働時間帯()); // 3.3.1
            }

            // 労働時間帯が講義時間帯に含まれる部分と含まれない部分がある場合
            if (  // 講義開始時間 が 労働開始時間 よりも 遅い　かつ　講義開始時間 が 労働終了時間 よりも 早い
                    (講義情報.講義時間帯().開始時間().compareTo(アルバイト情報.労働時間帯().開始時間()) > 0  &&  講義情報.講義時間帯().開始時間().compareTo(アルバイト情報.労働時間帯().終了時間()) < 0)
                            // 講義終了時間 が 労働開始時間 よりも 遅い　かつ　講義終了時間 が 労働終了時間 よりも 早い
                    ||  (講義情報.講義時間帯().終了時間().compareTo(アルバイト情報.労働時間帯().開始時間()) > 0  &&  講義情報.講義時間帯().終了時間().compareTo(アルバイト情報.労働時間帯().終了時間()) < 0) ) {
                通常労働時間帯と追加労働時間帯 = 時間割.通常労働時間帯と追加労働時間帯を作る(アルバイト情報.労働時間帯(), 講義情報.講義時間帯()); // 3.3.2
            }

            // 労働時間帯が講義時間帯に全て含まれない場合
            if (講義情報.講義時間帯().開始時間().compareTo(アルバイト情報.労働時間帯().終了時間()) >= 0 // 講義開始時間 が 労働終了時間 よりも 遅い
                    ||  講義情報.講義時間帯().終了時間().compareTo(アルバイト情報.労働時間帯().開始時間()) <= 0) { // 講義終了時間 が 労働開始時間 よりも 早い
                通常労働時間帯と追加労働時間帯 = 時間割.追加労働時間帯を作る(アルバイト情報.労働時間帯()); // 3.3.3
            }
        }

        労働情報表示.労働情報を出力する(アルバイト情報.日にち(), アルバイト情報.内容(), 通常労働時間帯と追加労働時間帯); // 4
    }
}
