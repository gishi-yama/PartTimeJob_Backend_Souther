package com.example.Backend.domain;

import com.example.Backend.domain.record.時間帯;
import com.example.Backend.domain.record.追加労働時間帯;
import com.example.Backend.domain.record.通常労働時間帯;
import com.example.Backend.domain.record.通常労働時間帯と追加労働時間帯;

public class 時間帯の管理 {

    public 通常労働時間帯と追加労働時間帯 通常労働時間帯を作る(時間帯 労働時間帯) { // 3.3.1
        通常労働時間帯 通常労働時間帯 = new 通常労働時間帯(労働時間帯.開始時間(), 労働時間帯.終了時間());
        return new 通常労働時間帯と追加労働時間帯(通常労働時間帯, null, null);
    }

    public 通常労働時間帯と追加労働時間帯 追加労働時間帯を作る(時間帯 労働時間帯){ // 3.2, 3.3.3
        追加労働時間帯 追加労働時間帯 = new 追加労働時間帯(労働時間帯.開始時間(), 労働時間帯.終了時間());
        return new 通常労働時間帯と追加労働時間帯(null,追加労働時間帯,null);
    }


    public 通常労働時間帯と追加労働時間帯 通常労働時間帯と追加労働時間帯を作る(時間帯 労働時間帯, 時間帯 講義時間帯){ // 3.3.2
        通常労働時間帯 通常労働時間帯 = new 通常労働時間帯();
        追加労働時間帯 追加労働時間帯 = new 追加労働時間帯();
        return new 通常労働時間帯と追加労働時間帯(通常労働時間帯, 追加労働時間帯, null);
    }

    public 通常労働時間帯と追加労働時間帯 通常労働時間帯と2つの追加労働時間帯を作る(時間帯 労働時間帯, 時間帯 講義時間帯){
        通常労働時間帯 通常労働時間帯 = new 通常労働時間帯(講義時間帯.開始時間(),講義時間帯.終了時間());
        追加労働時間帯 追加労働時間帯1 = new 追加労働時間帯(労働時間帯.開始時間(),講義時間帯.開始時間());
        追加労働時間帯 追加労働時間帯2 = new 追加労働時間帯(講義時間帯.終了時間(),労働時間帯.終了時間());
        return new 通常労働時間帯と追加労働時間帯(通常労働時間帯, 追加労働時間帯1, 追加労働時間帯2);
    }
}
