/**
 * 元の Java 版 {@link 労働時間帯分割} の特性テスト（Souther 移行時に追加）。
 *
 * <ul>
 *   <li>{@code 同じ入力で同じ結果}: src/main/souther/追加業務検知.examples.sou の
 *       「労働時間帯を分割する」の example と同じ 23 ケースを流し、Java 版が同じ結果を返すことを確かめる。
 *       これで Souther 版が既存の振る舞いを保っていることが分かる。</li>
 *   <li>{@code 現状の不具合}: Souther 版では型（invariant / sum）で作れなくなった入力に対する Java 版の挙動を記録する。</li>
 * </ul>
 */
class 労働時間帯分割の特性Test {

    static 通常労働時間帯と追加労働時間帯 分割する(String 講義の曜日, String 講義開始, String 講義終了,
                                               String 労働の曜日, String 労働開始, String 労働終了) {
        var 報告 = new 曜日付きアルバイト情報(
                new 学籍番号("b2240001"), new 学生の名前("千歳 太郎"),
                new アルバイトの日にち(LocalDate.of(2026, 11, 25)), new アルバイトの曜日(労働の曜日),
                new 時間帯(LocalTime.parse(労働開始), LocalTime.parse(労働終了)), new 業務内容("演習補助"));
        return new 労働時間帯分割()
                .算出する(new 講義の曜日(講義の曜日),
                        new 時間帯(LocalTime.parse(講義開始), LocalTime.parse(講義終了)),
                        new 曜日付きアルバイト情報リスト(List.of(報告)))
                .追加業務検知の結果リスト().getFirst().通常労働時間帯と追加労働時間帯();
    }

    static String 表示(LocalTime 開始, LocalTime 終了) {
        return 開始 + "~" + 終了;
    }

    static String 表示(通常労働時間帯と追加労働時間帯 r) {
        return String.join(" | ",
                r.通常労働時間帯() == null ? "-" : 表示(r.通常労働時間帯().開始時間(), r.通常労働時間帯().終了時間()),
                r.前にはみ出している追加労働時間帯() == null ? "-" : 表示(r.前にはみ出している追加労働時間帯().開始時間(), r.前にはみ出している追加労働時間帯().終了時間()),
                r.後ろにはみ出している追加労働時間帯() == null ? "-" : 表示(r.後ろにはみ出している追加労働時間帯().開始時間(), r.後ろにはみ出している追加労働時間帯().終了時間()),
                r.講義時間帯に全て含まれていない追加労働時間帯() == null ? "-" : 表示(r.講義時間帯に全て含まれていない追加労働時間帯().開始時間(), r.講義時間帯に全て含まれていない追加労働時間帯().終了時間()));
    }

    // 期待値の列: 通常 | 前の追加 | 後ろの追加 | 全て追加（"-" は null）。Souther の example の期待値を Java の 4 フィールドに写したもの。
    @ParameterizedTest(name = "{0}")
    @CsvSource(delimiter = ';', textBlock = """
            講義の無い曜日;               水;10:40;12:10;木;10:40;12:10;    - | - | - | 10:40~12:10
            講義の前に終わった;           水;10:40;12:10;水;09:00;10:00;    - | - | - | 09:00~10:00
            講義開始ちょうどに終わった;   水;10:40;12:10;水;09:00;10:40;    - | - | - | 09:00~10:40
            講義終了ちょうどから;         水;10:40;12:10;水;12:10;13:00;    - | - | - | 12:10~13:00
            講義時間ぴったり;             水;10:40;12:10;水;10:40;12:10;    10:40~12:10 | - | - | -
            講義時間の途中だけ;           水;10:40;12:10;水;11:00;11:30;    11:00~11:30 | - | - | -
            前から途中まで;               水;10:40;12:10;水;10:00;11:00;    10:40~11:00 | 10:00~10:40 | - | -
            前から終了ちょうどまで;       水;10:40;12:10;水;10:00;12:10;    10:40~12:10 | 10:00~10:40 | - | -
            途中から後まで;               水;10:40;12:10;水;11:30;13:00;    11:30~12:10 | - | 12:10~13:00 | -
            開始ちょうどから後まで;       水;10:40;12:10;水;10:40;13:00;    10:40~12:10 | - | 12:10~13:00 | -
            前から後まで;                 水;10:40;12:10;水;10:00;13:00;    10:40~12:10 | 10:00~10:40 | 12:10~13:00 | -
            月曜の講義・月曜の労働;       月;10:40;12:10;月;10:40;12:10;    10:40~12:10 | - | - | -
            火曜の講義・月曜の労働;       火;10:40;12:10;月;10:40;12:10;    - | - | - | 10:40~12:10
            木曜の講義・火曜の労働;       木;10:40;12:10;火;10:40;12:10;    - | - | - | 10:40~12:10
            金曜の講義・日曜の労働;       金;10:40;12:10;日;10:40;12:10;    - | - | - | 10:40~12:10
            土曜の講義・土曜の労働;       土;10:40;12:10;土;10:40;12:10;    10:40~12:10 | - | - | -
            日曜の講義・金曜の労働;       日;10:40;12:10;金;10:40;12:10;    - | - | - | 10:40~12:10
            開始の1秒後に終わった;        水;10:40;12:10;水;10:00;10:40:01; 10:40~10:40:01 | 10:00~10:40 | - | -
            開始の1秒前に始めた;          水;10:40;12:10;水;10:39:59;11:00; 10:40~11:00 | 10:39:59~10:40 | - | -
            終了の1秒前に始めた;          水;10:40;12:10;水;12:09:59;13:00; 12:09:59~12:10 | - | 12:10~13:00 | -
            終了の1秒後まで;              水;10:40;12:10;水;10:40;12:10:01; 10:40~12:10 | - | 12:10~12:10:01 | -
            前から終了1秒後まで;          水;10:40;12:10;水;10:00;12:10:01; 10:40~12:10 | 10:00~10:40 | 12:10~12:10:01 | -
            講義後しばらくして;           水;10:40;12:10;水;13:00;14:30;    - | - | - | 13:00~14:30
            """)
    void Souther版のexampleと同じ入力で同じ結果になる(String 名前, String 講義の曜日, String 講義開始, String 講義終了,
                                                 String 労働の曜日, String 労働開始, String 労働終了, String 期待) {
        assertEquals(期待.strip(), 表示(分割する(講義の曜日, 講義開始, 講義終了, 労働の曜日, 労働開始, 労働終了)));
    }

    // ---- 以下は Java 版の現状の挙動（不具合）の記録。Souther 版では型によってこの入力自体が作れない。----

    @Test
    void 不具合_長さ0の労働は通常労働と全て追加労働の両方になる() {
        // Souther: 時間帯 の invariant「開始は終了より前」で構築できない（E1903）
        assertEquals("10:40~10:40 | - | - | 10:40~10:40", 表示(分割する("水", "10:40", "12:10", "水", "10:40", "10:40")));
    }

    @Test
    void 不具合_開始と終了が逆の労働は通常労働として素通りする() {
        assertEquals("11:30~11:00 | - | - | -", 表示(分割する("水", "10:40", "12:10", "水", "11:30", "11:00")));
    }

    @Test
    void 不具合_曜日の表記ゆれは講義のない曜日として扱われる() {
        // Souther: 曜日 は 7 つの case のどれかなので "水曜" は Decoder で弾かれる
        assertEquals("- | - | - | 10:40~12:10", 表示(分割する("水", "10:40", "12:10", "水曜", "10:40", "12:10")));
    }
}
